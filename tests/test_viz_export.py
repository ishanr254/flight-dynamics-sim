"""Viewer export and the standalone property of the viewer folder."""

import json
import math
import re
from pathlib import Path

import numpy as np
import pytest

from src.aircraft import load_aircraft
from src.simulate import NonlinearAircraft, simulate_nonlinear
from src.viz import scenario, write_scenarios
from src.viz.export import GLOBAL

VIEWER = Path("viz")


@pytest.fixture(scope="module")
def exported():
    model = NonlinearAircraft(*load_aircraft("data/aircraft/df1_m1_asbuilt.toml"))

    def circle(t, out, m):      # hold a little aileron so the heading keeps turning
        return m.thrust_trim, 0.0, math.radians(-0.3), 0.0
    trajectory = simulate_nonlinear(model, 12.0, 0.01, controller=circle)
    return trajectory, scenario(trajectory, "test", "Test", "Manoeuvres", "A test flight.",
                                rate=30.0, span=1.2, summary=["one"], events=[(0.0, "start")])


def test_columns_are_uniformly_sampled_and_equal_length(exported):
    trajectory, s = exported
    lengths = {len(values) for values in s["columns"].values()}
    assert lengths == {int(round(s["duration"] * s["rate"])) + 1}
    assert s["duration"] == pytest.approx(trajectory.t[-1], abs=1 / s["rate"])


def test_attitude_is_exported_as_unit_quaternions(exported):
    _, s = exported
    q = np.array([s["columns"][f"q{i}"] for i in range(4)])
    assert np.linalg.norm(q, axis=0) == pytest.approx(1.0, abs=1e-4)


def test_heading_is_unwrapped_for_smooth_interpolation(exported):
    _, s = exported
    psi = np.array(s["columns"]["psi"])
    assert np.abs(np.diff(psi)).max() < 0.5 and abs(psi[-1]) > math.pi


def test_written_file_is_a_script_holding_valid_json(exported, tmp_path):
    _, s = exported
    path = write_scenarios(tmp_path / "data" / "scenarios.js", [s], "test")
    text = path.read_text()
    assert text.startswith("// Generated by test")
    payload = text.split(f"window.{GLOBAL} = ", 1)[1].rstrip().rstrip(";")
    assert json.loads(payload)[0]["id"] == "test"


def test_viewer_folder_is_self_contained():
    page = (VIEWER / "index.html").read_text()
    sources = re.findall(r'<(?:script|link|img)[^>]*(?:src|href)="([^"]+)"', page)
    assert sources == ["vendor/three.min.js", "data/scenarios.js"]
    assert all((VIEWER / source).exists() for source in sources)
    body = re.sub(r"<!--.*?-->", "", page, flags=re.DOTALL)
    assert not re.search(r"https?://|fetch\(|XMLHttpRequest|import\s*\(", body)


def test_shipped_scenarios_include_the_course_flight():
    text = (VIEWER / "data" / "scenarios.js").read_text()
    scenarios = json.loads(text.split(f"window.{GLOBAL} = ", 1)[1].rstrip().rstrip(";"))
    assert {s["id"] for s in scenarios} >= {"df1-m1-fastest", "df1-m1-limit", "df1-m1-course"}
    for course in (s for s in scenarios if s["group"] == "Course"):
        assert course["ground"]["half_length"] == pytest.approx(152.4)
        assert any("Lap 3 complete" == label for _, label in course["events"])
